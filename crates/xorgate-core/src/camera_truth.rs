/// The carrier connector a camera `dtoverlay=` line configures: a line with
/// a `cam0` token is `csi0`; every other camera line is `csi1`, WITH OR
/// WITHOUT a `cam1` token (`cam1` is not an overlay parameter: every camera
/// overlay targets CAM1 by default and `cam0` is the only port selector).
/// `None` = not a camera overlay this build knows ([`CAMERA_OVERLAYS`]).
pub fn port_of_line(line: &OverlayLine) -> Option<&'static str> {
    camera_overlay(&line.name)?;
    if line.params.iter().any(|p| p == "cam0") {
        Some("csi0")
    } else {
        Some("csi1")
    }
}

/// What config.txt says about one port (the wire `bootConfig`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BootConfigPort {
    /// The overlay of the port's line; `null` when no line targets the port.
    /// With several lines the LAST one is reported (the later overlay
    /// rewrites the port's endpoint, clock and regulator).
    pub overlay: Option<String>,
    /// That line as written in the file (trimmed).
    pub line: Option<String>,
    /// How many camera lines target the port. More than one is a fault.
    pub lines: usize,
}

/// The camera lines of `text` (a config.txt) that target `connector`.
/// Commented lines are skipped and `[section]` filters are not interpreted,
/// exactly like [`parse_overlay_lines`].
pub fn boot_config_port(text: &str, connector: &str) -> BootConfigPort {
    let lines = parse_overlay_lines(text);
    let mine: Vec<&OverlayLine> = lines
        .iter()
        .filter(|l| port_of_line(l) == Some(connector))
        .collect();
    BootConfigPort {
        overlay: mine.last().map(|l| l.name.clone()),
        line: mine.last().map(|l| l.text.trim().to_string()),
        lines: mine.len(),
    }
}

