/// How far "a driver is bound" proves which chip is attached.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Identity {
    /// The driver reads a chip ID at probe and refuses another chip
    /// (`imx219`, `imx708`, `imx477`): bound means it IS that sensor.
    ChipId,
    /// The driver checks one register for a fixed value another chip may
    /// also return (`imx335`): bound is a hint.
    Weak,
    /// The driver does no identity check at all (`imx290` and the overlays
    /// that use it): it binds to anything, so bound proves nothing.
    None,
}

impl Identity {
    pub fn as_str(self) -> &'static str {
        match self {
            Identity::ChipId => "chip-id",
            Identity::Weak => "weak",
            Identity::None => "none",
        }
    }
}

/// One camera overlay the agent recognises on a `dtoverlay=` line.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CameraOverlay {
    /// The overlay name (the first token of the line).
    pub name: &'static str,
    /// The kernel driver / device-tree node name the overlay instantiates,
    /// which is also what libcamera lists (`imx327` and `imx462` are served
    /// by the `imx290` driver and list as `imx290`).
    pub driver: &'static str,
    pub identity: Identity,
}

/// TEMPORARY (Phase 0): the camera overlays the agent recognises. Phase 1
/// replaces this table with the sensor catalog (`camera-catalog.json`,
/// generated by the backend); do not grow it into one.
///
/// Identity per driver, from the kernel sources on `rpi-6.12.y` and the
/// bench (plan PROGRESS.md, "Pass A — detection mechanics", item 5).
pub const CAMERA_OVERLAYS: &[CameraOverlay] = &[
    CameraOverlay {
        name: "imx219",
        driver: "imx219",
        identity: Identity::ChipId,
    },
    CameraOverlay {
        name: "imx290",
        driver: "imx290",
        identity: Identity::None,
    },
    CameraOverlay {
        name: "imx327",
        driver: "imx290",
        identity: Identity::None,
    },
    CameraOverlay {
        name: "imx335",
        driver: "imx335",
        identity: Identity::Weak,
    },
    CameraOverlay {
        name: "imx462",
        driver: "imx290",
        identity: Identity::None,
    },
    CameraOverlay {
        name: "imx477",
        driver: "imx477",
        identity: Identity::ChipId,
    },
    CameraOverlay {
        name: "imx708",
        driver: "imx708",
        identity: Identity::ChipId,
    },
];

/// The table entry of an overlay name, `None` for anything else (another
/// camera overlay included: Phase 0 does not know it).
pub fn camera_overlay(name: &str) -> Option<&'static CameraOverlay> {
    CAMERA_OVERLAYS.iter().find(|o| o.name == name)
}

/// The sensor a libcamera listing name stands for: libcamera appends the
/// module variant to some sensors (`imx708_wide`, `imx708_noir`,
/// `imx708_wide_noir`, `imx219_noir`, `imx477_noir`…), and every variant is
/// the same sensor as far as the declaration goes.
pub fn sensor_base(listed: &str) -> &str {
    for suffix in ["_wide_noir", "_noir", "_wide"] {
        if let Some(base) = listed.strip_suffix(suffix) {
            if !base.is_empty() {
                return base;
            }
        }
    }
    listed
}

/// Is the camera libcamera lists (`listed`) the sensor that was declared?
/// Variant names count as the sensor, and an overlay served by another
/// driver (`imx327`, `imx462` → `imx290`) matches what that driver lists.
pub fn same_sensor(declared: &str, listed: &str) -> bool {
    let base = sensor_base(listed);
    if base == declared || base == sensor_base(declared) {
        return true;
    }
    camera_overlay(declared).is_some_and(|o| o.driver == base)
}

